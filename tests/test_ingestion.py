
from pathlib import Path

import pymupdf

from services.ingestion_service import ingest_document


def create_sample_pdf(pdf_path: Path):
    """Create a small selectable-text PDF for testing."""

    document = pymupdf.open()
    page = document.new_page()

    sample_text = """
    BANK STATEMENT

    Account Holder: Test User
    Statement Period: 01-10-2026 to 31-10-2026

    DATE        DESCRIPTION             DEBIT       CREDIT      BALANCE
    01-10-2026  Opening Balance         0.00        0.00        10000.00
    05-10-2026  Grocery Purchase         1500.00     0.00        8500.00
    10-10-2026  Salary Credit            0.00        25000.00   33500.00
    15-10-2026  Electricity Bill         2200.00     0.00        31300.00
    """

    page.insert_text(
        (50, 50),
        sample_text,
        fontsize=10,
    )

    document.save(str(pdf_path))
    document.close()

    print(f"Sample PDF created: {pdf_path.name}")


def run_test():
    """Test the document ingestion pipeline."""

    test_directory = Path(__file__).resolve().parent
    sample_pdf_path = test_directory / "sample_financial_statement.pdf"

    try:
        # Step 1: Create a sample PDF.
        create_sample_pdf(sample_pdf_path)

        # Step 2: Run ingestion.
        # The document ID is generated by MySQL.
        result = ingest_document(
            pdf_path=sample_pdf_path,
            user_id=1,
        )

        # Step 3: Display the result.
        print("\nIngestion result:")
        print(result)

        # Step 4: Validate the result.
        if result.get("success"):
            print("\nPASS: End-to-end ingestion completed.")

            print(f"Document ID: {result.get('document_id')}")
            print(f"Filename: {result.get('filename')}")
            print(f"Document type: {result.get('document_type')}")
            print(f"Pages: {result.get('page_count')}")
            print(f"Characters: {result.get('character_count')}")
            print(f"Chunks: {result.get('chunk_count')}")

        else:
            print("\nFAIL: Ingestion did not complete.")
            print(f"Stage: {result.get('stage')}")
            print(f"Error: {result.get('message')}")

    except Exception as error:
        print("\nFAIL: Test raised an exception.")
        print(f"Error: {error}")
        raise

    finally:
        # Remove the generated sample PDF after testing.
        if sample_pdf_path.exists():
            sample_pdf_path.unlink()
            print("\nTemporary sample PDF removed.")


if __name__ == "__main__":
    run_test()
